/**
 * security/headers.mjs - the site's HTTP security headers, generated from data.
 *
 * `public/_headers` (Cloudflare's header file) is not a source file any more:
 * `npm run build` writes it (the kit's scripts/headers.mjs runs first, before
 * `astro build`) from inputs that each have one home:
 *
 *   1. our base policy: the six security headers and the cache rules for
 *      `/_astro/*` and `/favicon.svg` (BASE below; the same in every kit);
 *   2. the kit's own path rules: package.json → alderthemes.headers.paths
 *      (ours; e.g. a cache rule for `/hours-today.js`);
 *   3. the owner's data: src/data/headers.json (hosts to allow, the
 *      Cloudflare Web Analytics switch) and the booking/form addresses the
 *      kit names in package.json → alderthemes.headers.origins (read from the
 *      owner's data files, their origins go to `form-action` / `frame-src`);
 *   4. the content editor: when public/admin/config.yml exists the `/admin`
 *      policy is added (cms/headers.mjs → adminCsp);
 *   5. only in the studio's demo copy: src/data/demo-framing.json lets the
 *      store frame the demo (X-Frame-Options goes and the `frame-ancestors`
 *      directive names the store). The buyer's package never has that file.
 *
 * The order is fixed here; nothing else writes the file. The first two lines
 * of the output say where it came from and carry a digest of the inputs, so a
 * build that skipped that step (a host running `astro build` directly) is
 * caught by the kit's astro.config.mjs: it recomputes the digest with the same
 * rule (HEADER_INPUT_FILES + inputDigest, copied there without importing this
 * file) and stops when the file is missing or stale.
 *
 * Why generate: the policy is ours and must reach the owner with an update;
 * what the owner really needs (allow one host) is data and stays theirs.
 */
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { createHash } from "node:crypto";
import { adminCsp, BEGIN, END } from "../cms/headers.mjs";

/** The headers every kit must send on every page (kept as one list so it can be checked). */
export const REQUIRED_SECURITY_HEADERS = Object.freeze([
  "X-Content-Type-Options",
  "X-Frame-Options",
  "Referrer-Policy",
  "Permissions-Policy",
  "Strict-Transport-Security",
  "Content-Security-Policy",
]);

/**
 * The files whose bytes decide the output, in digest order. The kit's
 * astro.config.mjs keeps a literal copy of this list; a change here is a
 * change there (test/security-headers-gen.test.mjs holds the two together).
 */
export const HEADER_INPUT_FILES = Object.freeze([
  "src/data/headers.json",
  "src/data/site.json",
  "src/data/business.json",
  "package.json",
  "public/admin/config.yml",
  "src/data/demo-framing.json",
]);

/**
 * The only directives src/data/headers.json may add hosts to. frame-src is
 * here for embeds the data does not name (a map on the contact page); the
 * first host replaces 'none', the same way a booking widget's address does.
 */
export const ALLOW_DIRECTIVES = Object.freeze(["script-src", "connect-src", "img-src", "font-src", "style-src", "form-action", "frame-src"]);

/** The directives a kit may feed from the owner's data (package.json → alderthemes.headers.origins). */
export const DATA_ORIGIN_DIRECTIVES = Object.freeze(["form-action", "frame-src"]);

/** Cloudflare Web Analytics: the beacon script and where it reports. */
export const CLOUDFLARE_INSIGHTS = Object.freeze({
  "script-src": "https://static.cloudflareinsights.com",
  "connect-src": "https://cloudflareinsights.com",
});

export const GENERATED_LINE = "# Generated by `npm run build` from src/data/headers.json; edits here are replaced.";
export const DIGEST_PREFIX = "# Inputs: sha256:";

/** A problem in the owner's data: the file, then one line per field. */
export class HeadersError extends Error {
  constructor(file, lines) {
    super(["", `  ${file}: the security header settings are not valid.`, "", ...lines.map((l) => `    - ${l}`), "", "  Fix the file and build again.", ""].join("\n"));
    this.name = "HeadersError";
    this.file = file;
    this.lines = lines;
  }
}

/* ────────────────────────── digest ────────────────────────── */

/**
 * sha256 (first 16 hex) over the input files: name, then the bytes with CRLF
 * folded to LF (a Windows checkout and the host's Linux build must agree), a
 * missing file as the word "missing". The same rule lives inline in the kit's
 * astro.config.mjs.
 * @param {Array<[string, Buffer|string|null]>} entries
 */
export function inputDigest(entries) {
  const h = createHash("sha256");
  for (const [name, bytes] of entries) {
    h.update(`${name}\0`);
    h.update(bytes === null || bytes === undefined ? "missing" : String(bytes).replace(/\r\n/g, "\n"));
    h.update("\0");
  }
  return h.digest("hex").slice(0, 16);
}

/* ────────────────────────── inputs ────────────────────────── */

const isObj = (v) => v !== null && typeof v === "object" && !Array.isArray(v);
const ORIGIN = /^https:\/\/[A-Za-z0-9.-]+(?::\d{1,5})?$/;

/**
 * src/data/headers.json, checked. Missing text (no file) is the default:
 * analytics on, nothing extra allowed.
 * @param {string|null} text
 * @returns {{ cloudflareAnalytics: boolean, allow: Record<string, string[]> }}
 */
export function parseHeadersJson(text) {
  const FILE = "src/data/headers.json";
  const out = { cloudflareAnalytics: true, allow: Object.fromEntries(ALLOW_DIRECTIVES.map((d) => [d, []])) };
  if (text === null || text === undefined) return out;
  let data;
  try {
    data = JSON.parse(text);
  } catch (e) {
    throw new HeadersError(FILE, [`(the whole file): not valid JSON: ${e.message}`]);
  }
  const lines = [];
  if (!isObj(data)) throw new HeadersError(FILE, ['(the whole file): must be an object: { "cloudflareAnalytics": true, "allow": { ... } }']);
  for (const k of Object.keys(data)) {
    if (k !== "cloudflareAnalytics" && k !== "allow") lines.push(`${k}: not a setting. The settings are "cloudflareAnalytics" and "allow".`);
  }
  if ("cloudflareAnalytics" in data) {
    if (typeof data.cloudflareAnalytics !== "boolean") lines.push("cloudflareAnalytics: must be true or false");
    else out.cloudflareAnalytics = data.cloudflareAnalytics;
  }
  if ("allow" in data) {
    if (!isObj(data.allow)) lines.push(`allow: must be an object with one list per directive (${ALLOW_DIRECTIVES.join(", ")})`);
    else {
      for (const [dir, list] of Object.entries(data.allow)) {
        if (!ALLOW_DIRECTIVES.includes(dir)) {
          const why =
            dir === "frame-ancestors" || dir === "base-uri" || dir === "default-src"
              ? "it is part of the base policy and is not opened from data"
              : `the directives you can add hosts to are ${ALLOW_DIRECTIVES.join(", ")}`;
          lines.push(`allow.${dir}: not allowed here; ${why}.`);
          continue;
        }
        if (!Array.isArray(list)) {
          lines.push(`allow.${dir}: must be a list of origins, e.g. ["https://forms.example.com"]`);
          continue;
        }
        list.forEach((v, i) => {
          if (typeof v !== "string" || !ORIGIN.test(v)) {
            lines.push(`allow.${dir}[${i}]: ${JSON.stringify(v)} is not an https origin. Write the scheme and host only, e.g. "https://forms.example.com" (no path, no *, no 'unsafe-...', no data:).`);
          } else out.allow[dir].push(v);
        });
      }
    }
  }
  if (lines.length) throw new HeadersError(FILE, lines);
  return out;
}

/**
 * The origin of an address from the owner's data, or null when the address
 * is not a host: empty, "#" (the form posts nowhere) or a path on the site.
 * Anything else that is not https stops the build naming the field.
 * @param {unknown} value
 * @param {string} where  e.g. "src/data/site.json → reservation.formAction"
 */
export function originOf(value, where) {
  if (value === undefined || value === null) return null;
  if (typeof value !== "string") throw new HeadersError(where.split(" → ")[0], [`${where.split(" → ")[1] ?? where}: must be a text`]);
  const v = value.trim();
  if (v === "" || v === "#" || v.startsWith("/")) return null;
  let u;
  try {
    u = new URL(v);
  } catch {
    throw new HeadersError(where.split(" → ")[0], [`${where.split(" → ")[1] ?? where}: ${JSON.stringify(value)} is not an https address or a path starting with "/"`]);
  }
  if (u.protocol !== "https:") throw new HeadersError(where.split(" → ")[0], [`${where.split(" → ")[1] ?? where}: ${JSON.stringify(value)} must use https`]);
  return u.origin;
}

/** The value at a dotted path inside a parsed JSON value, or undefined. */
function at(obj, path) {
  let cur = obj;
  for (const p of path.split(".")) {
    if (!isObj(cur) || !(p in cur)) return undefined;
    cur = cur[p];
  }
  return cur;
}

/** `base_url:` of public/admin/config.yml (the login service), or null. */
export function authUrlOf(configYml) {
  if (configYml === null || configYml === undefined) return null;
  const m = /^\s*base_url:\s*["']?([^"'\s#]+)["']?\s*$/m.exec(configYml);
  return m ? m[1] : null;
}

/**
 * Everything buildHeaders needs, read from a kit folder (the kit's
 * scripts/headers.mjs calls this).
 * @param {string} kitDir
 * @returns {ReturnType<typeof buildHeaders> extends string ? object : never}
 */
export function collectKitInputs(kitDir) {
  const read = (rel) => {
    const p = join(kitDir, ...rel.split("/"));
    return existsSync(p) ? readFileSync(p) : null;
  };
  const text = (rel) => {
    const b = read(rel);
    return b === null ? null : b.toString("utf8");
  };
  const entries = HEADER_INPUT_FILES.map((f) => [f, read(f)]);
  const digest = inputDigest(entries);
  const pkgText = text("package.json");
  if (pkgText === null) throw new Error(`${kitDir}: package.json not found; is this the site folder?`);
  const pkg = JSON.parse(pkgText);
  const kit = isObj(pkg.alderthemes?.headers) ? pkg.alderthemes.headers : {};
  const paths = isObj(kit.paths) ? kit.paths : {};
  const origins = {};
  const jsonCache = new Map();
  const dataJson = (rel) => {
    if (!jsonCache.has(rel)) {
      const t = text(rel);
      jsonCache.set(rel, t === null ? null : JSON.parse(t));
    }
    return jsonCache.get(rel);
  };
  for (const [dir, pointers] of Object.entries(isObj(kit.origins) ? kit.origins : {})) {
    if (!DATA_ORIGIN_DIRECTIVES.includes(dir)) throw new Error(`package.json → alderthemes.headers.origins.${dir}: only ${DATA_ORIGIN_DIRECTIVES.join(", ")} are read from data`);
    if (!Array.isArray(pointers)) throw new Error(`package.json → alderthemes.headers.origins.${dir}: must be a list of "file#dotted.path" pointers`);
    origins[dir] = [];
    for (const ptr of pointers) {
      const [file, path] = String(ptr).split("#");
      if (!file || !path) throw new Error(`package.json → alderthemes.headers.origins.${dir}: "${ptr}" must be "src/data/<file>.json#dotted.path"`);
      const data = dataJson(file);
      if (data === null) continue;
      origins[dir].push({ value: at(data, path), where: `${file} → ${path}` });
    }
  }
  const framing = text("src/data/demo-framing.json");
  let demoFraming = null;
  if (framing !== null) {
    const f = JSON.parse(framing);
    if (!isObj(f) || typeof f.frameAncestors !== "string" || f.frameAncestors.trim() === "")
      throw new Error('src/data/demo-framing.json: expected { "frameAncestors": "<sources>" }');
    demoFraming = { frameAncestors: f.frameAncestors.trim() };
  }
  return {
    headersJson: text("src/data/headers.json"),
    paths,
    origins,
    adminConfigYml: text("public/admin/config.yml"),
    demoFraming,
    digest,
  };
}

/* ────────────────────────── output ────────────────────────── */

/** The base policy: six headers, every kit the same. */
const BASE_HEADERS = Object.freeze([
  ["X-Content-Type-Options", "nosniff"],
  ["X-Frame-Options", "DENY"],
  ["Referrer-Policy", "strict-origin-when-cross-origin"],
  ["Permissions-Policy", "camera=(), microphone=(), geolocation=(), payment=()"],
  ["Strict-Transport-Security", "max-age=31536000; includeSubDomains"],
]);

/** The base Content-Security-Policy, directive by directive, before the owner's hosts. */
function baseCsp(analytics) {
  return [
    ["default-src", ["'none'"]],
    ["script-src", ["'self'", ...(analytics ? [CLOUDFLARE_INSIGHTS["script-src"]] : [])]],
    ["style-src", ["'self'", "'unsafe-inline'"]],
    ["img-src", ["'self'", "data:"]],
    ["font-src", ["'self'"]],
    ["connect-src", ["'self'", ...(analytics ? [CLOUDFLARE_INSIGHTS["connect-src"]] : [])]],
    ["frame-src", ["'none'"]],
    ["frame-ancestors", ["'none'"]],
    ["base-uri", ["'self'"]],
    ["form-action", ["'self'"]],
  ];
}

const uniq = (list) => [...new Set(list)];

/**
 * The text of public/_headers.
 * @param {object} input
 * @param {string|null} [input.headersJson]   src/data/headers.json text, or null
 * @param {Record<string, Record<string,string>>} [input.paths]  kit path rules from package.json
 * @param {Record<string, Array<{value:unknown, where:string}>>} [input.origins]  data addresses per directive
 * @param {string|null} [input.adminConfigYml]  public/admin/config.yml text, or null when the editor is off
 * @param {{frameAncestors:string}|null} [input.demoFraming]  only the studio's demo copy
 * @param {string} [input.digest]  from inputDigest; written on line 2
 */
export function buildHeaders(input = {}) {
  const { headersJson = null, paths = {}, origins = {}, adminConfigYml = null, demoFraming = null, digest = "0000000000000000" } = input;
  const data = parseHeadersJson(headersJson);
  const csp = baseCsp(data.cloudflareAnalytics);
  const get = (dir) => csp.find(([d]) => d === dir)[1];

  /* 3. the owner's data: addresses → origins (form-action adds, frame-src replaces 'none'). */
  for (const [dir, list] of Object.entries(origins)) {
    if (!DATA_ORIGIN_DIRECTIVES.includes(dir)) throw new Error(`origins.${dir}: only ${DATA_ORIGIN_DIRECTIVES.join(", ")} are read from data`);
    const found = uniq(list.map(({ value, where }) => originOf(value, where)).filter(Boolean));
    if (found.length === 0) continue;
    const cur = get(dir);
    if (dir === "frame-src") cur.splice(0, cur.length, ...found);
    else cur.push(...found);
  }
  for (const dir of ALLOW_DIRECTIVES) {
    const cur = get(dir);
    for (const o of data.allow[dir]) {
      if (cur.includes("'none'")) cur.splice(cur.indexOf("'none'"), 1); /* frame-src: a host replaces 'none' */
      if (!cur.includes(o)) cur.push(o);
    }
  }

  /* 5. demo framing: the store frames the demo; never in the buyer's copy. */
  const headers = BASE_HEADERS.filter(([n]) => !(demoFraming && n === "X-Frame-Options"));
  if (demoFraming) get("frame-ancestors").splice(0, 1, ...demoFraming.frameAncestors.split(/\s+/));
  const cspText = csp.map(([d, v]) => `${d} ${v.join(" ")}`).join("; ");

  const analyticsNote = data.cloudflareAnalytics
    ? [
        "# Cloudflare Web Analytics injects a beacon script into every page when your",
        "# site is hosted on Cloudflare, and a strict script-src blocks it (console",
        "# errors, lower Lighthouse Best Practices). That is why its two hosts are",
        '# allowed. Not hosting on Cloudflare? Set "cloudflareAnalytics": false in',
        "# src/data/headers.json - the policy gets tighter and nothing breaks.",
      ]
    : ['# Cloudflare Web Analytics hosts are not allowed ("cloudflareAnalytics": false in', "# src/data/headers.json)."];

  const out = [
    GENERATED_LINE,
    `${DIGEST_PREFIX}${digest} (${HEADER_INPUT_FILES.join(", ")})`,
    "# Security headers.",
    "# Cloudflare Pages/Workers read this file.",
    "# Review it before you go live: https://developers.cloudflare.com/pages/configuration/headers/",
    "#",
    ...analyticsNote,
    "/*",
    ...headers.map(([n, v]) => `  ${n}: ${v}`),
    `  Content-Security-Policy: ${cspText}`,
    "",
    "# Two things this policy blocks until you allow them in your data:",
    "#",
    "# 1. A contact or booking form that posts to a form service. form-action is",
    "#    'self' plus the hosts of the form addresses in your data files; another",
    "#    host is blocked by the browser silently, the visitor sees nothing happen.",
    "#    Add it under \"allow\": { \"form-action\": [...] } in src/data/headers.json.",
    "# 2. An embed (a booking widget, a map) renders in an iframe, and frame-src is",
    "#    'none' until your booking settings name the widget's address or you add",
    "#    the embed's host under \"allow\": { \"frame-src\": [...] }.",
    "#    Scripts, images, fonts, styles and connections from another host go under",
    "#    \"allow\" in src/data/headers.json as well (https origins only).",
    "",
    "# Hashed build output never changes: the filename carries a content hash, so a",
    "# new build is a new URL. Without this the host serves it with a short default",
    "# lifetime, every repeat visit revalidates every asset, and Lighthouse flags",
    '# "use efficient cache lifetimes" on a site that has nothing to revalidate.',
    "# The fonts live here too - they are the largest thing a first visit pulls,",
    "# and they are hashed like everything else in this folder.",
    "/_astro/*",
    "  Cache-Control: public, max-age=31536000, immutable",
    "",
    "# These are NOT hashed: their names stay the same when their contents change.",
    "# So they get a lifetime, but never `immutable` - that would promise the file",
    "# can never change, and a visitor who cached it would keep the old one until",
    "# the promise expired. Without any rule at all they fall to the host's default",
    "# and cost a conditional request on every repeat page view.",
    "",
    "/favicon.svg",
    "  Cache-Control: public, max-age=604800",
  ];

  /* 2. the kit's own path rules, in the order package.json lists them. */
  for (const [path, rules] of Object.entries(paths)) {
    if (!/^\/[\w./*-]*$/.test(path)) throw new Error(`package.json → alderthemes.headers.paths: "${path}" is not a path pattern`);
    if (!isObj(rules) || Object.keys(rules).length === 0) throw new Error(`package.json → alderthemes.headers.paths["${path}"]: expected { "Header-Name": "value" }`);
    out.push("", path);
    for (const [n, v] of Object.entries(rules)) {
      if (typeof v !== "string" || v.trim() === "") throw new Error(`package.json → alderthemes.headers.paths["${path}"].${n}: must be a text`);
      out.push(`  ${n}: ${v}`);
    }
  }

  /* 4. the content editor's policy on /admin, when the editor is on. */
  if (adminConfigYml !== null) {
    const admin = adminCsp(authUrlOf(adminConfigYml));
    out.push("", BEGIN, "/admin", "  ! Content-Security-Policy", `  Content-Security-Policy: ${admin}`, "/admin/*", "  ! Content-Security-Policy", `  Content-Security-Policy: ${admin}`, END);
  }

  return out.join("\n") + "\n";
}

/**
 * The file for a kit folder: inputs read from disk, text built.
 * @param {string} kitDir
 * @returns {{ text: string, digest: string, editor: boolean, demoFraming: boolean }}
 */
export function buildKitHeaders(kitDir) {
  const input = collectKitInputs(kitDir);
  return { text: buildHeaders(input), digest: input.digest, editor: input.adminConfigYml !== null, demoFraming: input.demoFraming !== null };
}

/** `_headers` text without comment lines: what the host actually applies. */
export function withoutComments(text) {
  return String(text)
    .split(/\r?\n/)
    .filter((l) => !/^\s*#/.test(l))
    .join("\n");
}
